// PostgreSQL DDL from the translated schema (lib/db-driver/pg-schema.ts,
// postgres-schema.json). Plain JavaScript: scripts/db-migrate.mjs uses it
// without the TypeScript loader.

// Words Postgres reserves (fully, or as function/type names) that appear as
// identifiers; quoted in the DDL. Queries that use them (time_entries.end)
// must quote them as well.
export const RESERVED = new Set(
  "all analyse analyze and any array as asc asymmetric authorization binary both case cast check collate collation column concurrently constraint create cross current_catalog current_date current_role current_schema current_time current_timestamp current_user default deferrable desc distinct do else end except false fetch for foreign freeze from full grant group having ilike in initially inner intersect into is isnull join lateral leading left like limit localtime localtimestamp natural not notnull null offset on only or order outer overlaps placing primary references returning right select session_user similar some symmetric system_user table tablesample then to trailing true union unique user using variadic verbose when where window with".split(
    " ",
  ),
);
/** @param {string} name */
export const quoteIdent = (name) => (RESERVED.has(name.toLowerCase()) || !/^[a-z_][a-z0-9_]*$/.test(name) ? `"${name.replace(/"/g, '""')}"` : name);

/** @param {string} a */
const action = (a) => (/^(CASCADE|SET NULL|SET DEFAULT|RESTRICT)$/i.test(a) ? a.toUpperCase() : "NO ACTION");
/** @param {{ name: string; type: string; notNull: boolean; default: string | null; identity: boolean }} c */
export function columnDdl(c) {
  return `${quoteIdent(c.name)} ${c.type}${c.identity ? " GENERATED BY DEFAULT AS IDENTITY" : ""}${c.notNull ? " NOT NULL" : ""}${c.default !== null ? ` DEFAULT ${c.default}` : ""}`;
}
/** @param {{ name: string; columns: any[]; primaryKey: string[]; uniques: string[][]; checks: string[] }} t */
export function createTableSql(t) {
  const parts = t.columns.map(columnDdl);
  if (t.primaryKey.length) parts.push(`PRIMARY KEY(${t.primaryKey.map(quoteIdent).join(",")})`);
  for (const u of t.uniques) parts.push(`UNIQUE(${u.map(quoteIdent).join(",")})`);
  for (const c of t.checks) parts.push(`CHECK(${c})`);
  return `CREATE TABLE IF NOT EXISTS ${quoteIdent(t.name)}(${parts.join(",")})`;
}
/**
 * @param {{ name: string }} t
 * @param {{ name: string; columns: string[]; table: string; to: string[]; onDelete: string; onUpdate: string }} fk
 */
export function foreignKeySql(t, fk) {
  return `ALTER TABLE ${quoteIdent(t.name)} ADD CONSTRAINT ${quoteIdent(fk.name)} FOREIGN KEY(${fk.columns.map(quoteIdent).join(",")}) REFERENCES ${quoteIdent(fk.table)}(${fk.to.map(quoteIdent).join(",")}) ON DELETE ${action(fk.onDelete)} ON UPDATE ${action(fk.onUpdate)}`;
}

// Brings the Postgres schema up to `schema`: adds what is missing (tables,
// columns, indexes, foreign keys; never drops). `only` limits it to some
// tables (and their indexes and the foreign keys among them). `db` needs
// exec, all, run and columns (a Db of lib/db-driver, or the migration
// tool's own small wrapper).
/**
 * @param {{ exec(sql: string): Promise<void>; all(sql: string, ...p: any[]): Promise<any[]>; run(sql: string, ...p: any[]): Promise<unknown>; columns(t: string): Promise<string[]> }} db
 * @param {{ sqliteVersion: number; tables: any[]; indexes: { table: string; sql: string }[]; triggers?: any[]; seed?: { table: string; rows: Record<string, any>[] }[] }} schema
 * @param {string[]} [only]
 * @param {{ triggers?: boolean; seed?: boolean }} [options] false: no triggers (ensurePostgresTriggers after a data copy), no seed rows (a copy brings its own)
 */
export async function ensurePostgresSchema(db, schema, only, options = {}) {
  const tables = only ? schema.tables.filter((t) => only.includes(t.name)) : schema.tables;
  const names = new Set(tables.map((t) => t.name));
  await db.exec("CREATE TABLE IF NOT EXISTS flowplan_meta(key text PRIMARY KEY,value text NOT NULL)");
  for (const t of tables) {
    await db.exec(createTableSql(t));
    const have = new Set(await db.columns(t.name));
    for (const c of t.columns) if (!have.has(c.name)) await db.exec(`ALTER TABLE ${quoteIdent(t.name)} ADD COLUMN ${columnDdl(c)}`);
  }
  for (const index of schema.indexes) if (names.has(index.table)) await db.exec(index.sql);
  const existing = new Set(
    (await db.all("SELECT conname FROM pg_constraint WHERE connamespace=current_schema()::regnamespace AND contype='f'")).map((r) => r.conname),
  );
  for (const t of tables) for (const fk of t.foreignKeys) if (names.has(fk.table) && !existing.has(fk.name)) await db.exec(foreignKeySql(t, fk));
  // The rows the SQLite migrations write into a new database.
  for (const { table, rows } of options.seed === false ? [] : schema.seed || [])
    if (names.has(table))
      for (const row of rows) {
        const cols = Object.keys(row);
        await db.run(
          `INSERT INTO ${quoteIdent(table)}(${cols.map(quoteIdent).join(",")}) VALUES(${cols.map(() => "?").join(",")}) ON CONFLICT DO NOTHING`,
          ...cols.map((c) => (row[c] === "now" ? Date.now() : row[c])),
        );
      }
  if (options.triggers !== false) await ensurePostgresTriggers(db, schema, only);
  await db.run(
    "INSERT INTO flowplan_meta(key,value) VALUES('sqlite_schema',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
    String(schema.sqliteVersion),
  );
}
// The triggers (PL/pgSQL, lib/db-driver/pg-triggers.ts) on the given tables:
// CREATE OR REPLACE, so a changed trigger replaces the old one.
/**
 * @param {{ exec(sql: string): Promise<void> }} db
 * @param {{ triggers?: { table: string; sql: string }[] }} schema
 * @param {string[]} [only]
 */
export async function ensurePostgresTriggers(db, schema, only) {
  for (const t of schema.triggers || []) if (!only || only.includes(t.table)) await db.exec(t.sql);
}
