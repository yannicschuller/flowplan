#!/usr/bin/env node
// Generates the two thin API clients from the OpenAPI document (lib/openapi.ts):
//
//   npm run sdk        writes sdk/typescript/flowplan.ts and sdk/python/flowplan_client.py
//
// No dependencies beyond Node (and tsx to load lib/openapi.ts). The output
// is deterministic; tests/openapi.test.ts fails when the committed files
// differ from a fresh run, so the SDKs never drift from the specification.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const outputs = {
  typescript: "sdk/typescript/flowplan.ts",
  python: "sdk/python/flowplan_client.py",
};
const HEADER = "Generated by scripts/generate-sdk.mjs from the Flowplan OpenAPI document (lib/openapi.ts). Do not edit by hand; run `npm run sdk`.";

export function generateSdks(doc) {
  const ops = operationsOf(doc);
  return { typescript: typescriptSdk(doc, ops), python: pythonSdk(doc, ops) };
}

// ---- The document as operations ----

const refName = (schema) => schema.$ref.split("/").pop();
const pascal = (name) => name.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toUpperCase());
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`).replace(/[^a-z0-9_]+/g, "_");
const camel = (name) => name.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));

function operationsOf(doc) {
  const ops = [];
  for (const [path, item] of Object.entries(doc.paths))
    for (const [method, op] of Object.entries(item)) {
      const params = op.parameters || [];
      const bodyContent = op.requestBody ? Object.keys(op.requestBody.content)[0] : null;
      const okStatus = Object.keys(op.responses).find((s) => s.startsWith("2"));
      const ok = okStatus ? op.responses[okStatus] : null;
      const okContent = ok?.content ? Object.keys(ok.content)[0] : null;
      ops.push({
        id: op.operationId,
        method: method.toUpperCase(),
        path,
        summary: op.summary || "",
        description: op.description || "",
        pathParams: params.filter((p) => p.in === "path"),
        queryParams: params.filter((p) => p.in === "query"),
        body: bodyContent ? { content: bodyContent, schema: op.requestBody.content[bodyContent].schema, required: op.requestBody.required !== false } : null,
        response: okContent ? { content: okContent, schema: ok.content[okContent].schema } : null,
        // Takes an Idempotency-Key: the clients send one and keep it on retries.
        idempotent: !!op["x-idempotent"],
      });
    }
  return ops;
}
const isJson = (content) => content === "application/json";
const isForm = (content) => content === "multipart/form-data";
const docLine = (op) => [op.summary, op.description].filter(Boolean).join(" — ");

// ---- TypeScript ----

function tsType(s, indent = "  ") {
  if (!s || typeof s !== "object") return "unknown";
  if (s.$ref) return pascal(refName(s));
  const variants = s.oneOf || s.anyOf;
  if (variants) return [...new Set(variants.map((v) => tsType(v, indent)))].join(" | ");
  if (s.allOf) return s.allOf.map((v) => wrap(tsType(v, indent))).join(" & ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  let types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (!types.length) types = s.properties || s.additionalProperties ? ["object"] : [];
  if (!types.length) return "unknown";
  return types
    .map((t) => {
      if (t === "string") return "string";
      if (t === "number" || t === "integer") return "number";
      if (t === "boolean") return "boolean";
      if (t === "null") return "null";
      if (t === "array") return `${wrap(tsType(s.items, indent))}[]`;
      if (t === "object") return tsObject(s, indent);
      return "unknown";
    })
    .join(" | ");
}
const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);
function tsObject(s, indent) {
  const extra = s.additionalProperties;
  if (!s.properties) return extra && typeof extra === "object" && Object.keys(extra).length ? `Record<string, ${tsType(extra, indent)}>` : "Record<string, unknown>";
  const required = new Set(s.required || []);
  const inner = indent + "  ";
  const lines = Object.entries(s.properties).map(([name, prop]) => {
    const comment = prop.description ? `${inner}/** ${prop.description.replace(/\*\//g, "*\\/")} */\n` : "";
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
    return `${comment}${inner}${key}${required.has(name) ? "" : "?"}: ${tsType(prop, inner)};`;
  });
  if (extra) lines.push(`${inner}[key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}
// Multipart bodies: binary fields are Blobs, everything else a string.
function tsFormType(schema) {
  const required = new Set(schema.required || []);
  const lines = Object.entries(schema.properties || {}).map(([name, prop]) => {
    const binary = prop.format === "binary" || prop.items?.format === "binary";
    const type = binary ? (prop.type === "array" ? "Blob[]" : "Blob") : tsType(prop, "    ");
    return `    ${name}${required.has(name) ? "" : "?"}: ${type};`;
  });
  return `{\n${lines.join("\n")}\n  }`;
}

// `CommandResultOf<A>`: for every action schema with a `…Result` sibling.
function commandResultType(doc) {
  const command = doc.components.schemas.Command;
  if (!command?.oneOf) return null;
  const cases = command.oneOf
    .map((v) => refName(v))
    .filter((name) => doc.components.schemas[`${name}Result`])
    .map((name) => {
      const action = doc.components.schemas[name].properties.action;
      return `A extends { action: ${JSON.stringify(action.const ?? action.enum[0])} } ? ${pascal(name)}Result :`;
    });
  return cases.length ? `export type CommandResultOf<A extends Command> = ${cases.join(" ")} CommandResult;` : null;
}

function typescriptSdk(doc, ops) {
  const out = [];
  out.push(`// ${HEADER}`);
  out.push(`// ${doc.info.title}: ${doc.info.summary || ""}`.trimEnd());
  out.push("");
  out.push("// ---- Types from the specification ----");
  out.push("");
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    if (schema.description) out.push(`/** ${schema.description.replace(/\*\//g, "*\\/")} */`);
    out.push(`export type ${pascal(name)} = ${tsType(schema, "")};`);
    out.push("");
  }
  const resultOf = commandResultType(doc);
  if (resultOf) out.push("/** The result of a command action, by the action sent. */", resultOf, "");
  out.push(`// ---- Client ----

export interface ClientOptions {
  /** Address of the instance, e.g. https://flowplan.example.com */
  baseUrl: string;
  /** Personal API token (fp_…); read tokens may only call GET endpoints and the Markdown export. */
  token?: string;
  /** Your own fetch (tests, proxies); defaults to the global one. */
  fetch?: typeof fetch;
  /** Headers sent with every request. */
  headers?: Record<string, string>;
  /**
   * Retries of GET requests and of changes that take an Idempotency-Key, after a network error,
   * 429, 502, 503, 504 or 409 while the first attempt still runs (default 2). Changes are retried
   * with the same key, so they are applied once.
   */
  retries?: number;
}
export interface RequestOptions {
  signal?: AbortSignal;
  headers?: Record<string, string>;
  /** The Idempotency-Key of this call (default: a new UUID per call for operations that take one). Pass the same key to repeat the same action later. */
  idempotencyKey?: string;
  /** Retries of this call (default: the client's). */
  retries?: number;
}
export type Query = Record<string, string | number | boolean | undefined | null>;

/** An answer with a status outside 2xx. \`message\` is the server's text in the reader's language. */
export class FlowplanError extends Error {
  constructor(
    readonly status: number,
    message: string,
    /** Validation messages (400). */
    readonly details?: string[],
    /** Seconds to wait (429). */
    readonly retryAfter?: number,
  ) {
    super(message);
    this.name = "FlowplanError";
  }
}

export class FlowplanClient {
  constructor(private readonly options: ClientOptions) {}

  /** Any request; the generated methods build on it. */
  async request(
    method: string,
    path: string,
    init: { query?: Query; json?: unknown; form?: Record<string, unknown>; raw?: BodyInit; contentType?: string; idempotent?: boolean } = {},
    options: RequestOptions = {},
  ): Promise<Response> {
    const url = new URL(this.options.baseUrl.replace(/\\/$/, "") + path);
    for (const [key, value] of Object.entries(init.query || {}))
      if (value !== undefined && value !== null) url.searchParams.set(key, String(value));
    const headers = new Headers({ ...this.options.headers, ...options.headers });
    if (this.options.token) headers.set("Authorization", \`Bearer \${this.options.token}\`);
    headers.set("Accept", "application/json, */*;q=0.8");
    let body: BodyInit | undefined;
    if (init.json !== undefined) {
      headers.set("Content-Type", "application/json");
      body = JSON.stringify(init.json);
    } else if (init.form) {
      const data = new FormData();
      for (const [key, value] of Object.entries(init.form)) {
        if (value === undefined || value === null) continue;
        for (const item of Array.isArray(value) ? value : [value])
          data.append(key, item instanceof Blob ? item : String(item));
      }
      body = data;
    } else if (init.raw !== undefined) {
      if (init.contentType) headers.set("Content-Type", init.contentType);
      body = init.raw;
    }
    // One key per call, the same on every retry of it.
    const key = options.idempotencyKey ?? (init.idempotent ? globalThis.crypto.randomUUID() : undefined);
    if (key) headers.set("Idempotency-Key", key);
    const retries = method === "GET" || key ? (options.retries ?? this.options.retries ?? 2) : 0;
    for (let attempt = 0; ; attempt++) {
      let response: Response;
      try {
        response = await (this.options.fetch || fetch)(url, { method, headers, body, signal: options.signal });
      } catch (error) {
        if (attempt >= retries || options.signal?.aborted) throw error;
        await FlowplanClient.pause(attempt, null);
        continue;
      }
      if (attempt < retries && (await FlowplanClient.retryable(response))) {
        await response.body?.cancel();
        await FlowplanClient.pause(attempt, response.headers.get("Retry-After"));
        continue;
      }
      if (!response.ok) throw await FlowplanClient.error(response);
      return response;
    }
  }

  private static async retryable(response: Response) {
    if ([429, 502, 503, 504].includes(response.status)) return true;
    if (response.status !== 409) return false;
    try {
      return ((await response.clone().json()) as { code?: string })?.code === "idempotency_in_progress";
    } catch {
      return false;
    }
  }

  private static pause(attempt: number, retryAfter: string | null) {
    const seconds = Number(retryAfter);
    const ms = seconds > 0 ? Math.min(seconds, 30) * 1000 : 500 * 2 ** attempt;
    return new Promise((resolve) => setTimeout(resolve, ms));
  }

  private async json<T>(method: string, path: string, init: Parameters<FlowplanClient["request"]>[2] = {}, options?: RequestOptions): Promise<T> {
    const response = await this.request(method, path, init, options);
    const text = await response.text();
    return (text ? JSON.parse(text) : undefined) as T;
  }

  private static async error(response: Response) {
    let message = \`\${response.status} \${response.statusText}\`.trim();
    let details: string[] | undefined;
    try {
      const body = (await response.json()) as { error?: string; details?: string[] };
      if (body?.error) message = body.error;
      details = body?.details;
    } catch {}
    const retry = Number(response.headers.get("Retry-After"));
    return new FlowplanError(response.status, message, details, retry > 0 ? retry : undefined);
  }
`);
  for (const op of ops) {
    const args = [];
    const callInit = [];
    for (const prm of op.pathParams) args.push(`${camel(prm.name)}: string`);
    if (op.queryParams.length) {
      const required = op.queryParams.some((prm) => prm.required);
      const props = op.queryParams.map((prm) => `${prm.name}${prm.required ? "" : "?"}: ${tsType(prm.schema, "    ")}`);
      args.push(`query${required ? "" : "?"}: { ${props.join("; ")} }`);
      callInit.push("query");
    }
    if (op.body) {
      if (isJson(op.body.content)) {
        args.push(`body: ${tsType(op.body.schema, "  ")}`);
        callInit.push("json: body");
      } else if (isForm(op.body.content)) {
        args.push(`form: ${tsFormType(op.body.schema)}`);
        callInit.push("form");
      } else {
        args.push("body: Blob | ArrayBuffer");
        callInit.push(`raw: body`, `contentType: ${JSON.stringify(op.body.content)}`);
      }
    }
    args.push("options?: RequestOptions");
    const path = "`" + op.path.replace(/\{([^}]+)\}/g, (_, name) => "${encodeURIComponent(" + camel(name) + ")}") + "`";
    if (op.idempotent) callInit.push("idempotent: true");
    const initText = callInit.length ? `{ ${callInit.join(", ")} }` : "{}";
    const jsonAnswer = op.response && isJson(op.response.content);
    let returnType = jsonAnswer ? tsType(op.response.schema, "  ") : op.response ? "Response" : "void";
    let generic = "";
    // The command endpoint: the result type follows the action sent.
    if (op.body && isJson(op.body.content) && op.body.schema?.$ref === "#/components/schemas/Command" && resultOf) {
      generic = "<A extends Command>";
      args[args.indexOf("body: Command")] = "body: A";
      returnType = "CommandResultOf<A>";
    }
    out.push(`  /** ${docLine(op).replace(/\*\//g, "*\\/")} (${op.method} ${op.path}) */`);
    out.push(`  async ${op.id}${generic}(${args.join(", ")}): Promise<${returnType}> {`);
    if (jsonAnswer) out.push(`    return this.json<${returnType}>(${JSON.stringify(op.method)}, ${path}, ${initText}, options);`);
    else if (op.response) out.push(`    return this.request(${JSON.stringify(op.method)}, ${path}, ${initText}, options);`);
    else out.push(`    await this.request(${JSON.stringify(op.method)}, ${path}, ${initText}, options);`);
    out.push("  }");
    out.push("");
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}

// ---- Python ----

function pyType(s) {
  if (!s || typeof s !== "object") return "Any";
  if (s.$ref) return `"${pascal(refName(s))}"`;
  const variants = s.oneOf || s.anyOf;
  if (variants) return pyUnion(variants.map(pyType));
  if (s.allOf) return "dict[str, Any]";
  if (s.enum) return `Literal[${s.enum.map(pyLiteral).join(", ")}]`;
  if (s.const !== undefined) return `Literal[${pyLiteral(s.const)}]`;
  let types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (!types.length) types = s.properties || s.additionalProperties ? ["object"] : [];
  if (!types.length) return "Any";
  return pyUnion(
    types.map((t) => {
      if (t === "string") return "str";
      if (t === "integer") return "int";
      if (t === "number") return "float";
      if (t === "boolean") return "bool";
      if (t === "null") return "None";
      if (t === "array") return `list[${pyType(s.items)}]`;
      if (t === "object") {
        const extra = s.additionalProperties;
        return !s.properties && extra && typeof extra === "object" && Object.keys(extra).length ? `dict[str, ${pyType(extra)}]` : "dict[str, Any]";
      }
      return "Any";
    }),
  );
}
const pyLiteral = (v) => (v === null ? "None" : typeof v === "boolean" ? (v ? "True" : "False") : JSON.stringify(v));
function pyUnion(types) {
  const unique = [...new Set(types)];
  if (unique.length === 1) return unique[0];
  if (unique.length === 2 && unique.includes("None")) return `Optional[${unique.find((t) => t !== "None")}]`;
  return `Union[${unique.join(", ")}]`;
}
function pyTypedDict(name, schema) {
  const required = new Set(schema.required || []);
  const lines = Object.entries(schema.properties || {}).map(([key, prop]) => {
    const type = required.has(key) ? `Required[${pyType(prop)}]` : pyType(prop);
    const comment = prop.description ? `  # ${prop.description.replace(/\n/g, " ")}` : "";
    return `    ${JSON.stringify(key)}: ${type},${comment}`;
  });
  return `${name} = TypedDict(${JSON.stringify(name)}, {\n${lines.join("\n")}\n}, total=False)`;
}
function pyFormDict(name, schema) {
  const required = new Set(schema.required || []);
  const lines = Object.entries(schema.properties || {}).map(([key, prop]) => {
    const binary = prop.format === "binary" || prop.items?.format === "binary";
    const base = binary ? (prop.type === "array" ? "list[FormFile]" : "FormFile") : pyType(prop);
    return `    ${JSON.stringify(key)}: ${required.has(key) ? `Required[${base}]` : base},`;
  });
  return `${name} = TypedDict(${JSON.stringify(name)}, {\n${lines.join("\n")}\n}, total=False)`;
}
const pyDoc = (text) => text.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');

function pythonSdk(doc, ops) {
  const out = [];
  out.push(`"""${doc.info.title}: ${doc.info.summary || ""}

${HEADER}

Only the standard library is used (urllib). Python 3.11 or newer.
"""
from __future__ import annotations

import json as _json
import time as _time
import uuid as _uuid
from typing import Any, Literal, Optional, Required, TypedDict, Union
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlencode
from urllib.request import Request, urlopen

__all__ = ["FlowplanClient", "FlowplanError", "FormFile"]

# A file in a multipart form: (filename, content, mime type).
FormFile = tuple[str, bytes, str]

# ---- Types from the specification ----
`);
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    if (schema.description) out.push(`# ${schema.description.replace(/\n/g, " ")}`);
    out.push(schema.type === "object" && schema.properties ? pyTypedDict(pascal(name), schema) : `${pascal(name)} = ${pyType(schema)}`);
    out.push("");
  }
  const queryDicts = [];
  for (const op of ops) {
    if (op.queryParams.length) {
      const name = `${pascal(op.id)}Query`;
      const schema = {
        properties: Object.fromEntries(op.queryParams.map((prm) => [prm.name, { ...prm.schema, description: prm.description }])),
        required: op.queryParams.filter((prm) => prm.required).map((prm) => prm.name),
      };
      queryDicts.push(pyTypedDict(name, schema));
    }
    if (op.body && isForm(op.body.content)) queryDicts.push(pyFormDict(`${pascal(op.id)}Form`, op.body.schema));
  }
  out.push("# ---- Parameters of the operations ----", "", ...queryDicts.flatMap((d) => [d, ""]));
  out.push(`# ---- Client ----


class FlowplanError(Exception):
    """An answer with a status outside 2xx; \`message\` is the server's text in the reader's language."""

    def __init__(self, status: int, message: str, details: Optional[list[str]] = None, retry_after: Optional[int] = None):
        super().__init__(f"{status}: {message}")
        self.status = status
        self.message = message
        self.details = details or []
        self.retry_after = retry_after


def _p(value: Any) -> str:
    return quote(str(value), safe="")


def _pause(attempt: int, retry_after: Optional[int]) -> None:
    _time.sleep(min(retry_after, 30) if retry_after else 0.5 * 2**attempt)


class FlowplanClient:
    """Calls a Flowplan instance with a personal API token (fp_…)."""

    def __init__(self, base_url: str, token: Optional[str] = None, timeout: float = 60.0, headers: Optional[dict[str, str]] = None, retries: int = 2):
        """\`retries\`: GET requests and changes with an Idempotency-Key are retried after a network error,
        429, 502, 503, 504 or 409 while the first attempt still runs – changes with the same key, so they
        are applied once."""
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.timeout = timeout
        self.headers = dict(headers or {})
        self.retries = retries

    def request(
        self,
        method: str,
        path: str,
        query: Optional[dict[str, Any]] = None,
        json_body: Any = None,
        form: Optional[dict[str, Any]] = None,
        raw: Optional[bytes] = None,
        content_type: Optional[str] = None,
        headers: Optional[dict[str, str]] = None,
        idempotent: bool = False,
        idempotency_key: Optional[str] = None,
        retries: Optional[int] = None,
    ) -> tuple[int, dict[str, str], bytes]:
        """Any request: status, headers and body. Raises FlowplanError outside 2xx.

        Operations that take an Idempotency-Key get a new one per call (or \`idempotency_key\`),
        kept on every retry of that call."""
        url = self.base_url + path
        params = {k: v for k, v in (query or {}).items() if v is not None}
        if params:
            url += "?" + urlencode({k: str(v).lower() if isinstance(v, bool) else v for k, v in params.items()})
        send = dict(self.headers)
        send.update(headers or {})
        if self.token:
            send["Authorization"] = f"Bearer {self.token}"
        send.setdefault("Accept", "application/json, */*;q=0.8")
        data: Optional[bytes] = None
        if json_body is not None:
            send["Content-Type"] = "application/json"
            data = _json.dumps(json_body).encode("utf-8")
        elif form is not None:
            boundary = _uuid.uuid4().hex
            send["Content-Type"] = f"multipart/form-data; boundary={boundary}"
            data = _multipart(form, boundary)
        elif raw is not None:
            if content_type:
                send["Content-Type"] = content_type
            data = raw
        key = idempotency_key or (str(_uuid.uuid4()) if idempotent else None)
        if key:
            send["Idempotency-Key"] = key
        attempts = (self.retries if retries is None else retries) if method == "GET" or key else 0
        attempt = 0
        while True:
            try:
                with urlopen(Request(url, data=data, method=method, headers=send), timeout=self.timeout) as response:
                    return response.status, dict(response.headers.items()), response.read()
            except HTTPError as error:
                body = error.read()
                message = f"{error.code} {error.reason}".strip()
                details: Optional[list[str]] = None
                code: Optional[str] = None
                try:
                    parsed = _json.loads(body.decode("utf-8"))
                    message = parsed.get("error") or message
                    details = parsed.get("details")
                    code = parsed.get("code")
                except Exception:
                    pass
                retry = error.headers.get("Retry-After")
                wait = int(retry) if retry and retry.isdigit() else None
                if attempt < attempts and (error.code in (429, 502, 503, 504) or (error.code == 409 and code == "idempotency_in_progress")):
                    _pause(attempt, wait)
                    attempt += 1
                    continue
                raise FlowplanError(error.code, message, details, wait) from None
            except URLError:
                if attempt >= attempts:
                    raise
                _pause(attempt, None)
                attempt += 1

    def _json(self, method: str, path: str, **kwargs: Any) -> Any:
        _, _, body = self.request(method, path, **kwargs)
        return _json.loads(body.decode("utf-8")) if body else None

    def _bytes(self, method: str, path: str, **kwargs: Any) -> bytes:
        return self.request(method, path, **kwargs)[2]
`);
  for (const op of ops) {
    const args = ["self"];
    const call = [];
    for (const prm of op.pathParams) args.push(`${snake(prm.name)}: str`);
    if (op.body) {
      if (isJson(op.body.content)) {
        args.push(`body: ${pyType(op.body.schema)}`);
        call.push("json_body=body");
      } else if (isForm(op.body.content)) {
        args.push(`form: "${pascal(op.id)}Form"`);
        call.push("form=dict(form)");
      } else {
        args.push("body: bytes");
        call.push("raw=body", `content_type=${JSON.stringify(op.body.content)}`);
      }
    }
    if (op.queryParams.length) {
      const required = op.queryParams.some((prm) => prm.required);
      args.push(required ? `query: "${pascal(op.id)}Query"` : `query: Optional["${pascal(op.id)}Query"] = None`);
      call.push("query=dict(query) if query else None");
    }
    args.push("headers: Optional[dict[str, str]] = None");
    call.push("headers=headers");
    if (op.idempotent) {
      args.push("idempotency_key: Optional[str] = None");
      call.push("idempotent=True", "idempotency_key=idempotency_key");
    }
    const path = op.path.split(/(\{[^}]+\})/).filter(Boolean).map((part) => (part.startsWith("{") ? `_p(${snake(part.slice(1, -1))})` : JSON.stringify(part))).join(" + ");
    const jsonAnswer = op.response && isJson(op.response.content);
    const returnType = jsonAnswer ? pyType(op.response.schema) : op.response ? "bytes" : "None";
    out.push(`    def ${snake(op.id)}(${args.join(", ")}) -> ${returnType}:`);
    out.push(`        """${pyDoc(docLine(op))} (${op.method} ${op.path})"""`);
    if (jsonAnswer) out.push(`        return self._json(${JSON.stringify(op.method)}, ${path}, ${call.join(", ")})`);
    else if (op.response) out.push(`        return self._bytes(${JSON.stringify(op.method)}, ${path}, ${call.join(", ")})`);
    else out.push(`        self.request(${JSON.stringify(op.method)}, ${path}, ${call.join(", ")})`);
    out.push("");
  }
  out.push(`
def _multipart(form: dict[str, Any], boundary: str) -> bytes:
    """Encodes strings, bytes and FormFile tuples (also lists of them) as multipart/form-data."""
    parts: list[bytes] = []
    for name, value in form.items():
        if value is None:
            continue
        for item in value if isinstance(value, list) else [value]:
            head = f'--{boundary}\\r\\nContent-Disposition: form-data; name="{name}"'
            if isinstance(item, tuple):
                filename, content, mime = item
                head += f'; filename="{filename}"\\r\\nContent-Type: {mime}'
            else:
                content = item if isinstance(item, bytes) else str(item).encode("utf-8")
            parts.append(head.encode("utf-8") + b"\\r\\n\\r\\n" + content + b"\\r\\n")
    return b"".join(parts) + f"--{boundary}--\\r\\n".encode("utf-8")
`);
  return out.join("\n");
}

