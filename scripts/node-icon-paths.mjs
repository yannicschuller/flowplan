#!/usr/bin/env node
// Writes lib/workflows/node-icon-paths.ts: the SVG path data (Phosphor,
// "regular" weight, viewBox 0 0 256 256) of every symbol the node catalogue
// names, plus the fallback circle. The marketplace draws node symbols from
// these paths (payload/workflow-meta.json, lib/marketplace-workflow-meta.ts)
// without loading any script or icon font.
//
//   node --import tsx scripts/node-icon-paths.mjs
//
// tests/marketplace-workflow-meta.test.ts checks that the file is complete
// and matches the installed icon package.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const { NODE_TYPES } = await import("../lib/workflows/catalog.ts");

export async function iconPath(name) {
  const mod = await import(join(root, "node_modules/@phosphor-icons/react/dist/defs", `${name}.es.js`));
  const element = mod.default.get("regular");
  const children = [element.props.children].flat();
  const paths = children.filter((c) => c && c.type === "path").map((c) => c.props.d);
  if (!paths.length || paths.length !== children.length) throw new Error(`${name}: only <path> elements are supported`);
  return paths.join(" ");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const names = [...new Set([...NODE_TYPES.map((n) => n.icon), "Circle"])].sort();
  const lines = [];
  for (const name of names) lines.push(`  ${name}: ${JSON.stringify(await iconPath(name))},`);
  const out = `// Generated by scripts/node-icon-paths.mjs – do not edit by hand.
// SVG path data of the node symbols (Phosphor Icons, MIT licence, "regular"
// weight, viewBox 0 0 256 256, filled).
export const NODE_ICON_PATHS: Record<string, string> = {
${lines.join("\n")}
};
`;
  writeFileSync(join(root, "lib/workflows/node-icon-paths.ts"), out);
  console.log(`${names.length} icons → lib/workflows/node-icon-paths.ts`);
}
