export function LibraryIcon({
  value,
  size = 18,
  className,
}: {
  value: string;
  size?: number;
  className?: string;
}) {
  const parsed = parseLibraryIcon(value);
  const Symbol = parsed && libraryIcons[parsed.name];
  if (!parsed || !Symbol) return null;
  return (
    <Symbol
      size={size}
      color={parsed.color}
      weight="duotone"
      className={className}
      aria-hidden="true"
    />
  );
}
