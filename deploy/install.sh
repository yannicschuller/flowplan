#!/usr/bin/env bash
# Flowplan on any server with Ubuntu 24.04 or Debian 12 – one command:
#
#   curl -fsSL https://raw.githubusercontent.com/yannicschuller/flowplan/main/deploy/install.sh | sudo bash -s -- flowplan.example.com
#
# Without a domain, Flowplan starts at http://<server address> without HTTPS
# (for trying out only). Run the script again with a domain later to switch
# to HTTPS; the data and generated secrets stay.
#
# What it does:
#   - installs Docker Engine and the Compose plugin from Docker's repository
#   - writes /opt/flowplan: compose.yaml (Flowplan + Caddy, which gets the
#     HTTPS certificate itself), Caddyfile and a .env (mode 0600) with
#     secrets generated by openssl on this server
#   - opens only SSH, 80 and 443 in the firewall (ufw)
#   - turns on automatic security updates of the system (unattended-upgrades)
#   - optionally a weekly image update (systemd timer flowplan-update.timer)
#   - writes the details to /root/flowplan-README.txt
#
# Settings (environment variables, all optional):
#   FLOWPLAN_ACME_EMAIL=you@example.com  e-mail for Let's Encrypt notices
#   FLOWPLAN_AUTO_UPDATE=weekly          pull and restart the image weekly
#                                        (default off: you update by hand)
#   FLOWPLAN_VERSION=latest              image tag (latest, 0.9, 0.9.1, beta)
#   FLOWPLAN_FIREWALL=off                leave the firewall alone
#   FLOWPLAN_DIR=/opt/flowplan           installation folder
#
# Docs: https://docs.flowplan.org/en/one-click-deploy#any-server-cloud-init-or-install-script
set -euo pipefail

IMAGE=ghcr.io/yannicschuller/flowplan
DIR="${FLOWPLAN_DIR:-/opt/flowplan}"
README=/root/flowplan-README.txt

# Waits for the package lock: on a fresh server, apt's own daily jobs often
# hold it during the first minutes.
apt_get() { apt-get -o DPkg::Lock::Timeout=600 "$@" </dev/null; }
log() { printf '\n==> %s\n' "$*"; }
die() { printf '\nError: %s\n' "$*" >&2; exit 1; }

# The public address without a domain: the source address of the default
# route, which is the public one on almost every VPS (not behind NAT).
server_address() {
  local ip
  ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") { print $(i + 1); exit }}')
  if [ -n "$ip" ]; then printf '%s' "$ip"; return; fi
  ip=$(ip -6 route get 2606:4700:4700::1111 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") { print $(i + 1); exit }}')
  if [ -n "$ip" ]; then printf '[%s]' "$ip"; return; fi
  hostname -I 2>/dev/null | awk '{print $1}'
}

install_docker() {
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    log "Docker with the Compose plugin is already installed"
    return
  fi
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${ID:-}" in
    ubuntu | debian) ;;
    *) die "Docker is missing and ${PRETTY_NAME:-this system} is not Ubuntu or Debian. Install Docker with the Compose plugin first (https://docs.docker.com/engine/install/), then run this script again." ;;
  esac
  log "Installing Docker from download.docker.com"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/$ID/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/$ID ${VERSION_CODENAME} stable" \
    >/etc/apt/sources.list.d/docker.list
  apt_get update -q
  apt_get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
}

# KEY=value in .env: replaced when present, appended otherwise.
set_env() {
  local key=$1 value=$2 file="$DIR/.env"
  if grep -q "^$key=" "$file"; then
    sed -i "s|^$key=.*|$key=$value|" "$file"
  else
    printf '%s=%s\n' "$key" "$value" >>"$file"
  fi
}
get_env() { sed -n "s/^$1=//p" "$DIR/.env" | head -n 1; }

write_files() {
  local domain=$1 app_url=$2 email=$3
  install -d -m 0755 "$DIR"

  cat >"$DIR/compose.yaml" <<'EOF'
# Flowplan with Caddy in front (written by deploy/install.sh).
# Settings and secrets: .env next to this file. After a change:
#   docker compose up -d
# Update by hand: docker compose pull && docker compose up -d
services:
  flowplan:
    image: ghcr.io/yannicschuller/flowplan:${FLOWPLAN_VERSION:-latest}
    env_file: .env
    environment:
      FLOWPLAN_DATA_DIR: /app/data
    volumes:
      - flowplan-data:/app/data
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 30s
      timeout: 5s
      start_period: 20s
      retries: 3

  caddy:
    image: caddy:2
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config
    depends_on:
      - flowplan
    restart: unless-stopped

volumes:
  # All Flowplan data: database, uploads, keys, local backups.
  flowplan-data:
  caddy-data:
  caddy-config:
EOF

  {
    echo "# Written by deploy/install.sh – run it again with a domain to change it."
    if [ -n "$domain" ]; then
      if [ -n "$email" ]; then printf '{\n\temail %s\n}\n\n' "$email"; fi
      printf '%s {\n\treverse_proxy flowplan:3000\n}\n' "$domain"
    else
      echo "# No domain yet: plain http on port 80, no certificate."
      printf ':80 {\n\treverse_proxy flowplan:3000\n}\n'
    fi
  } >"$DIR/Caddyfile"

  if [ ! -f "$DIR/.env" ]; then
    log "Generating secrets in $DIR/.env"
    (
      umask 077
      cat >"$DIR/.env" <<EOF
# Flowplan settings (https://docs.flowplan.org/en/configuration).
# Generated on this server by deploy/install.sh. Keep a copy of
# FLOWPLAN_ENCRYPTION_KEY somewhere safe (password manager): encrypted
# backups and exports can only be read with it.
APP_URL=$app_url
FLOWPLAN_SETUP_TOKEN=$(openssl rand -hex 24)
FLOWPLAN_ENCRYPTION_KEY=$(openssl rand -base64 32)
# Caddy is the one proxy in front of Flowplan.
FLOWPLAN_TRUSTED_PROXIES=1
FLOWPLAN_VERSION=${FLOWPLAN_VERSION:-latest}
# E-mail for invitations and forgotten passwords:
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=
EOF
    )
  else
    log "Keeping the existing $DIR/.env and its secrets"
    set_env APP_URL "$app_url"
    if [ -n "${FLOWPLAN_VERSION:-}" ]; then set_env FLOWPLAN_VERSION "$FLOWPLAN_VERSION"; fi
  fi
  chmod 600 "$DIR/.env"
}

setup_firewall() {
  if [ "${FLOWPLAN_FIREWALL:-on}" = off ]; then
    log "Firewall left alone (FLOWPLAN_FIREWALL=off)"
    return
  fi
  log "Firewall: SSH, 80 and 443"
  apt_get install -y -q ufw
  local port
  # Keep every port sshd listens on open, not only 22.
  for port in $(sshd -T 2>/dev/null | awk '$1 == "port" {print $2}') 22; do
    ufw allow "$port/tcp" >/dev/null
  done
  ufw allow 80/tcp >/dev/null
  ufw allow 443/tcp >/dev/null
  ufw allow 443/udp >/dev/null
  ufw --force enable >/dev/null
  ufw status verbose || true
}

setup_unattended_upgrades() {
  log "Automatic security updates (unattended-upgrades)"
  apt_get install -y -q unattended-upgrades
  cat >/etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF
}

setup_update_timer() {
  cat >/etc/systemd/system/flowplan-update.service <<EOF
[Unit]
Description=Update the Flowplan image and restart it
After=docker.service network-online.target
Wants=network-online.target
Requires=docker.service

[Service]
Type=oneshot
WorkingDirectory=$DIR
ExecStart=/usr/bin/docker compose pull --quiet
ExecStart=/usr/bin/docker compose up -d
ExecStart=/usr/bin/docker image prune -f
EOF
  cat >/etc/systemd/system/flowplan-update.timer <<'EOF'
[Unit]
Description=Weekly Flowplan image update

[Timer]
OnCalendar=Sun *-*-* 04:00:00
RandomizedDelaySec=1h
Persistent=true

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  if [ "${FLOWPLAN_AUTO_UPDATE:-off}" = weekly ]; then
    systemctl enable --now flowplan-update.timer
    log "Weekly image update: on (flowplan-update.timer)"
  else
    log "Weekly image update: off (turn on: systemctl enable --now flowplan-update.timer)"
  fi
}

ports_in_use() {
  # Ports 80/443 held by something other than our Caddy container.
  if [ -n "$(cd "$DIR" && docker compose ps -q caddy 2>/dev/null)" ]; then return 1; fi
  ss -Hltn 2>/dev/null | awk '{print $4}' | grep -Eq '(^|:)(80|443)$'
}

wait_healthy() {
  local id status _
  id=$(cd "$DIR" && docker compose ps -q flowplan)
  for _ in $(seq 1 60); do
    status=$(docker inspect --format '{{.State.Health.Status}}' "$id" 2>/dev/null || echo unknown)
    if [ "$status" = healthy ]; then return 0; fi
    sleep 3
  done
  echo "Flowplan has not reported healthy yet ($status). Check: cd $DIR && docker compose logs flowplan" >&2
  return 0
}

write_readme() {
  local domain=$1 app_url=$2 token
  token=$(get_env FLOWPLAN_SETUP_TOKEN)
  (
    umask 077
    cat >"$README" <<EOF
Flowplan on this server
=======================

Address:        $app_url
First account:  $app_url/register?setup=$token
                (the setup link works until the first account exists; it
                becomes the administrator)

Files:          $DIR/compose.yaml   Flowplan + Caddy
                $DIR/Caddyfile      the domain and HTTPS
                $DIR/.env           settings and secrets (mode 0600)
Data:           Docker volume flowplan-data (/app/data in the container)

IMPORTANT: copy FLOWPLAN_ENCRYPTION_KEY from $DIR/.env into a password
manager. Encrypted backups and exports cannot be read without it.

EOF
    if [ -z "$domain" ]; then
      cat >>"$README" <<EOF
No domain is set: Flowplan runs WITHOUT HTTPS. Fine for a test, not for real
use (passwords cross the network unencrypted; passkeys, push and the apps
need HTTPS). To switch to a domain:
  1. Point the domain's DNS A (and AAAA) record to this server.
  2. Run the install script again with the domain:
     curl -fsSL https://raw.githubusercontent.com/yannicschuller/flowplan/main/deploy/install.sh | sudo bash -s -- flowplan.example.com
     Data and secrets stay. Do this before creating accounts if you can:
     passkeys are bound to the address.

EOF
    fi
    cat >>"$README" <<EOF
Update by hand:   cd $DIR && docker compose pull && docker compose up -d
Weekly updates:   systemctl enable --now flowplan-update.timer   (off: disable --now)
Logs:             cd $DIR && docker compose logs -f flowplan
E-mail (SMTP):    fill in SMTP_* in $DIR/.env, then: cd $DIR && docker compose up -d
Backups:          Administration → Storage & backup; off-site with S3, see
                  https://docs.flowplan.org/en/storage-and-backups
All settings:     https://docs.flowplan.org/en/configuration
EOF
  )
}

main() {
  [ "$(id -u)" -eq 0 ] || die "Run as root, e.g. with sudo."
  umask 022
  local domain="${1:-${FLOWPLAN_DOMAIN:-}}" email="${FLOWPLAN_ACME_EMAIL:-}" app_url
  # Accept https://flowplan.example.com/ as well.
  domain="${domain#http://}"
  domain="${domain#https://}"
  domain="${domain%%/*}"
  if [ -n "$domain" ] && ! printf '%s' "$domain" | grep -Eq '^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$'; then
    die "\"$domain\" is not a domain name like flowplan.example.com."
  fi
  if [ -n "$email" ] && ! printf '%s' "$email" | grep -Eq '^[^[:space:]@{}]+@[^[:space:]@{}]+$'; then
    die "FLOWPLAN_ACME_EMAIL \"$email\" is not an e-mail address."
  fi
  case "${FLOWPLAN_VERSION:-latest}" in *[!A-Za-z0-9._-]*) die "FLOWPLAN_VERSION must be an image tag like latest or 0.9.1." ;; esac

  export DEBIAN_FRONTEND=noninteractive
  log "Installing the basics"
  apt_get update -q
  apt_get install -y -q ca-certificates curl openssl iproute2

  install_docker

  if [ -n "$domain" ]; then
    app_url="https://$domain"
  else
    app_url="http://$(server_address)"
    [ "$app_url" != "http://" ] || die "Could not find this server's address. Run the script with a domain."
  fi

  write_files "$domain" "$app_url" "$email"
  if ports_in_use; then
    die "Port 80 or 443 is already in use by another program (a web server?). Free them, or put Flowplan behind that server instead: https://docs.flowplan.org/en/coolify-and-proxy"
  fi
  setup_firewall
  setup_unattended_upgrades
  setup_update_timer

  log "Starting Flowplan ($IMAGE:${FLOWPLAN_VERSION:-$(get_env FLOWPLAN_VERSION)})"
  (cd "$DIR" && docker compose pull --quiet && docker compose up -d)
  wait_healthy
  write_readme "$domain" "$app_url"

  log "Done"
  cat "$README"
  if [ -n "$domain" ]; then
    echo
    echo "HTTPS needs the domain's DNS record to point to this server; Caddy fetches the certificate on the first request."
  fi
}

main "$@"
