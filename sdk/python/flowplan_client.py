def _multipart(form: dict[str, Any], boundary: str) -> bytes:
    """Encodes strings, bytes and FormFile tuples (also lists of them) as multipart/form-data."""
    parts: list[bytes] = []
    for name, value in form.items():
        if value is None:
            continue
        for item in value if isinstance(value, list) else [value]:
            head = f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"'
            if isinstance(item, tuple):
                filename, content, mime = item
                head += f'; filename="{filename}"\r\nContent-Type: {mime}'
            else:
                content = item if isinstance(item, bytes) else str(item).encode("utf-8")
            parts.append(head.encode("utf-8") + b"\r\n\r\n" + content + b"\r\n")
    return b"".join(parts) + f"--{boundary}--\r\n".encode("utf-8")
